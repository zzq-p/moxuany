CREATE TABLE IF NOT EXISTS food_product_option (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,product_id BIGINT NOT NULL,kind VARCHAR(10) NOT NULL,
 name VARCHAR(60) NOT NULL,price INT NOT NULL,stock INT NOT NULL DEFAULT 0,active TINYINT NOT NULL DEFAULT 1,
 version BIGINT NOT NULL DEFAULT 0,INDEX idx_option_product(product_id,active,id),
 CHECK(price>=0),CHECK(stock>=0)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS food_refund (
 id VARCHAR(40) PRIMARY KEY,order_id VARCHAR(40) NOT NULL,member_id BIGINT NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'REQUESTED',reason VARCHAR(500) NOT NULL,
 reply VARCHAR(500) NOT NULL DEFAULT '',amount INT NOT NULL,restocked TINYINT NOT NULL DEFAULT 0,
 requested_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,resolved_at DATETIME NULL,
 INDEX idx_refund_order(order_id,requested_at,id)
) ENGINE=InnoDB;
